import cv2, numpy as np
im=cv2.imread('lid.jpg').astype(np.float32)
src=np.float32([(457,141),(1375,161),(378,2066),(1416,2064)])
Wd,Hd=1000,2040
M=cv2.getPerspectiveTransform(src,np.float32([(0,0),(Wd,0),(0,Hd),(Wd,Hd)]))
f=cv2.warpPerspective(im,M,(Wd,Hd),flags=cv2.INTER_CUBIC,borderMode=cv2.BORDER_REPLICATE)
cv2.imwrite('lidflat.png',f)
g=f.min(2)
bg=cv2.morphologyEx(g,cv2.MORPH_CLOSE,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(31,31)))
bg=cv2.GaussianBlur(bg,(0,0),10)
a=np.clip((bg-g)/(bg*.45+1e-3),0,1); a=np.clip((a-.12)/.5,0,1)
# цвет штриха: пиксель фото, делённый на фон (красный клинок и пламя остаются красными)
bgc=cv2.GaussianBlur(cv2.morphologyEx(f,cv2.MORPH_CLOSE,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(31,31))),(0,0),10)
col=np.clip(f/(bgc+1e-3),0,1)
cv2.imwrite('lidink.png',np.dstack([col*255,a*255]).astype(np.uint8))
v=cv2.cvtColor((255-a*255).astype(np.uint8),cv2.COLOR_GRAY2BGR)
for x in range(0,Wd,100): cv2.line(v,(x,0),(x,Hd),(0,0,255),1); cv2.putText(v,str(x),(x+2,14),cv2.FONT_HERSHEY_SIMPLEX,.45,(0,0,255),1)
for y in range(0,Hd,100): cv2.line(v,(0,y),(Wd,y),(255,0,0),1); cv2.putText(v,str(y),(2,y+14),cv2.FONT_HERSHEY_SIMPLEX,.45,(255,0,0),1)
cv2.imwrite('lidgrid.png',cv2.resize(v,(500,1020),interpolation=cv2.INTER_AREA))
